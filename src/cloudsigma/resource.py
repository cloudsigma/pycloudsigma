class KeyPair(ResourceBase):
    """
    Keypairs (SSH keys) resource.

    The keypairs resource can be used to store SSH keys, for use with your servers.
    You have three choices when creating a keypair:
    1. Provide both private and public key.
    2. Provide only a public key, in which case the private key will remain empty.
    3. Provide no public, neither private key, in which case a new RSA or ED25519
       keypair will be automatically generated by specifying `algorithm_type`.

    Keys attached to a server appear in the server context and can be automatically
    added to `authorized_keys` for OS images supporting cloudinit upon reboot.
    """
    resource_name = 'keypairs'

    # The inherited methods from ResourceBase (get, list, create, update, delete)
    # are sufficient for managing keypairs, as specific parameters like
    # 'algorithm_type' for creation are passed as part of the data payload.



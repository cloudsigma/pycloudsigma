class Drive(ResourceBase):
    resource_name = 'drives'

    def clone(self, uuid, data=None, avoid=None):
        """
        Clone a drive.

        :param uuid:
            Source drive for the clone.
        :param data:
            Clone drive options. Refer to API docs for possible options.
        :param avoid:
            A list of drive or server uuids to avoid for the clone.
            Avoid attempts to put the clone on a different physical storage
            host from the drives in *avoid*.
            If a server uuid is in *avoid* it is internally expanded
            to the drives attached to the server.
        :return:
            Cloned drive definition.
        """
        data = data or {}
        query_params = {}
        if avoid:
            if isinstance(avoid, basestring):
                avoid = [avoid]
            query_params['avoid'] = ','.join(avoid)

        return self._action(uuid, 'clone', data, query_params=query_params)

    def resize(self, uuid, data=None):
        """
        Resize a drive. Raises an error if drive is mounted on a running
        server or unavailable.
        :param uuid:
            UUID of the drive.
        :param data:
            Drive definition containing the new size.
        :return:
        """
        data = data or {}
        return self._action(uuid, 'resize', data)

    def create(self, data, avoid=None):
        """
        Create a drive.

        :param data:
            Drive definition.
        :param avoid:
            A list of drive or server uuids to avoid for the new drive.
            Avoid attempts to put the drive on a different physical storage
            host from the drives in *avoid*. If a server uuid is in *avoid*
            it is internally expanded to the drives attached to the server.
        :return:
            New drive definition.
        """
        query_params = {}
        if avoid:
            if isinstance(avoid, basestring):
                avoid = [avoid]
            query_params['avoid'] = ','.join(avoid)
        return super(Drive, self).create(data, query_params=query_params)

    def get_upload_chunk_link(self, uuid, chunk_number, chunk_size=5 * 1024 ** 2):
        """
        Get an upload URL for a give chunk
        :param uuid:
            UUID of the drive. Needs to be in *uploading* state
        :type uuid: basestring
        :param chunk_number:
            The number of the chunk to upload. Counting starts from 0 and last chunk is bigger in size, for example
            if drive is 5MiB and chunks are 2MiB each, the last chunk (chunk 1) is 3MiB.
        :type chunk_number: int
        :param chunk_size:
            Size of the upload chunk in bytes. For example use 2 * 1024 ** 2 for 2MiB chunks.
        :type chunk_size: int
        :return:
            A link to upload the chunk to. The link does not require authentication and is valid for 5 minutes
        :rtype: str
        """
        res_data = self._action(uuid, 'upload_chunk', {'chunk_number': chunk_number, 'chunk_size': chunk_size})
        return res_data['link']

    def upload_chunk(self, link, image_path, chunk_number, chunk_size):
        chunk_offset = chunk_number * chunk_size
        file_size = os.path.getsize(image_path)
        n_chunks = file_size // chunk_size
        if n_chunks == 0:
            real_chunk_size = file_size
        elif chunk_number < n_chunks - 1:
            real_chunk_size = chunk_size
        else:
            real_chunk_size = file_size - chunk_offset
        with open(image_path, 'rb') as f: # Changed 'r' to 'rb' for binary file reading
            f.seek(chunk_offset)
            data = f.read(real_chunk_size)

        headers = {
            'User-Agent': 'CloudSigma turlo client',
            'Content-Type': 'application/octet-stream',
            'Accept': 'application/json'
        }
        return requests.post(self.c._get_full_url(link), data=data, headers=headers)

    def set_scheduler(self, drive_uuid, backup_policy_uuid):
        """
        Link a backup scheduler to a drive.

        :param drive_uuid:
            UUID of the drive to link the scheduler to.
        :type drive_uuid: basestring
        :param backup_policy_uuid:
            UUID of the backup scheduler policy to set.
        :type backup_policy_uuid: basestring
        :return:
            The updated drive definition.
        """
        data = {'backup_policy_uuid': backup_policy_uuid}
        return self._action(drive_uuid, 'set_scheduler', data=data)


class InitUpload(ResourceBase):
    resource_name = 'initupload'

    def create(self, data, avoid=None, image_path=None):
        """
        Create a drive for upload.

        :param data:
            Drive definition. Note that the size of the drive should be equal to the exact file size to be uploaded up
            to a KiB. The image format should be raw disk image.
        :param avoid:
            A list of drive or server uuids to avoid for the new drive. Avoid attempts to put the drive on a different
            physical storage host from the drives in *avoid*. If a server uuid is in *avoid* it is internally expanded
            to the drives attached to the server.
        :param image_path:
            A path to the drive image to be uploaded. If given, and no name is specified in data, filename will be used
            as a drive name, also if the size parameter is not preset the file size will be used.
        :return:
            New drive definition.
        """
        query_params = {}
        if not data.get('name'):
            data['name'] = os.path.split(image_path)[1]
        if not data.get('size'):
            data['size'] = os.path.getsize(image_path)
        if avoid:
            if isinstance(avoid, basestring):
                avoid = [avoid]
            query_params['avoid'] = ','.join(avoid)
        return super(InitUpload, self).create(data, query_params=query_params)


class Server(ResourceBase):
    resource_name = 'servers'

    def start(self, uuid, allocation_method=None):
        """
        Starts a server with specific UUID.

        :param uuid:
            UUID of the server to start.
        :type uuid: basestring
        :param allocation_method:
            Optional allocation method (e.g., 'auto').
        :type allocation_method: basestring or None
        :return:
            Action result.
        """
        data = {}
        if allocation_method:
            data = {'allocation_method': str(allocation_method)}
        return self._action(uuid, 'start', data)

    def stop(self, uuid):
        """
        Stops a server with specific UUID. This action is equivalent to pulling the power cord of a physical server.
        For more graceful shutdown see :py:meth:`shutdown`.

        :param uuid:
            UUID of the server to stop.
        :type uuid: basestring
        :return:
            Action result.
        """
        return self._action(
            uuid,
            'stop',
            data={}  # Workaround API issue - see TUR-1346
        )

    def restart(self, uuid):
        return self._action(
            uuid,
            'restart',
            data={}  # Workaround API issue - see TUR-1346
        )

    def shutdown(self, uuid):
        """
        Sends an ACPI shutdowns to a server with specific UUID for a minute.
        If the VM OS handles ACPI shutdown events (equivalent to pressing the power button),
        it will shutdown gracefully. As some operating systems don’t always
        handle single ACPI event the shutdown is sent every second for a minute.
        While the shutdown is initiated, the server is put into status ``stopping``
        to prevent interfering actions. If after a minute the server has not
        powered off during this minute the status is returned to ``running``
        to allow the user to :py:meth:`stop` it. If the server shuts down successfully
        during the one minute period it will be switched to ``stopped`` status.

        :param uuid:
            UUID of the server to shut down.
        :type uuid: basestring
        :return:
            Action result.
        """
        return self._action(
            uuid,
            'shutdown',
            data={}  # Workaround API issue - see TUR-1346
        )

    def runtime(self, uuid):
        url = self._get_url() + uuid + '/runtime/'
        return self.c.get(url, return_list=False)

    def open_vnc(self, uuid):
        return self._action(uuid, 'open_vnc', data={})

    def close_vnc(self, uuid):
        return self._action(uuid, 'close_vnc', data={})

    def open_console(self, uuid):
        """
        Opens a serial console connection for a server.

        Each server has a virtual serial device, which is tunneled to a TCP socket.
        The serial device is seen as /dev/ttyS0 or COM1 on most operating systems.
        If your OS supports it, you can configure a serial console on this virtual
        serial port, which might be more convenient to use than VNC, as it generally
        uses less bandwidth and allows you to copy-paste in the virtual terminal.

        :param uuid:
            UUID of the server.
        :type uuid: basestring
        :return:
            A dictionary containing the console URL.
        :rtype: dict
        """
        res_data = self._action(uuid, 'open_console')
        return res_data['console_url']

    def close_console(self, uuid):
        """
        Closes a serial console connection to a server with specific UUID.

        :param uuid:
            UUID of the server.
        :type uuid: basestring
        :return:
            Action result.
        """
        return self._action(uuid, 'close_console', data={})

    def clone(self, uuid, name=None, random_vnc_password=None, data=None, avoid=None):
        """
        Clones a server. Does cascading clone of server drives, i.e. all disk drives
        attached to the server are cloned and attached to the new server. CDROM drives
        attached to the clone source are attached to the clone. IPs of the cloned server
        are set to DHCP. All other properties of the clone are equal to the original.

        The optional `data` dictionary can contain other clone server options.
        The optional `name` attribute will be the name of the newly-cloned server.
        The `random_vnc_password` boolean attribute, if set, will generate a new vnc
        password for the new server.
        The `avoid` parameter is a list of drive or server uuids to avoid for the clone.
        Avoid attempts to put the cloned drives on a different physical storage
        host from the drives in *avoid*. If a server uuid is in *avoid* it
        is internally expanded to the drives attached to the server.

        :param uuid:
            Source server for the clone.
        :type uuid: basestring
        :param name:
            Name of the cloned server.
        :type name: basestring or None
        :param random_vnc_password:
            If true, a new VNC password will be generated for the cloned server.
        :type random_vnc_password: bool or None
        :param data:
            Clone server options. Refer to API docs for possible options.
        :type data: dict or None
        :param avoid:
            A list of drive or server uuids to avoid for the clone.
        :type avoid: list of basestring or basestring or None
        :return:
            Cloned server definition.
        """
        _data = data or {}
        if name is not None:
            _data['name'] = name
        if random_vnc_password is not None:
            _data['random_vnc_password'] = random_vnc_password

        query_params = {}
        if avoid:
            if isinstance(avoid, basestring):
                avoid = [avoid]
            query_params['avoid'] = ','.join(avoid)

        return self._action(uuid, 'clone', data=_data, query_params=query_params)

    def delete(self, uuid, recurse=None):
        """
        Deletes a server.

        :param uuid:
            uuid of the server to delete
        :param recurse:
            option to recursively delete attached drives. Possible values are
            'all_drives', 'disks', 'cdroms'. It is possible to use one of the supplied
            convenience functions: delete_all_attached_drives, delete_disks,
            delete_cdroms

        :return:
        """
        query_params = {}
        if recurse is not None:
            query_params.update(recurse=recurse)
        if not query_params:
            query_params = None

        return super(Server, self).delete(uuid, query_params=query_params)

    def delete_all_attached_drives(self, uuid):
        """
        Deletes a server together with all its attached drives (recursive delete).

        :param uuid:
            UUID of the server to delete.
        :type uuid: basestring
        :return:
            Response from the API.
        """
        return self.delete(uuid, recurse='all_drives')

    def delete_disks(self, uuid):
        """
        Deletes a server together with its attached disk drives, leaving CDROMs intact.

        :param uuid:
            UUID of the server to delete.
        :type uuid: basestring
        :return:
            Response from the API.
        """
        return self.delete(uuid, recurse='disks')

    def delete_cdroms(self, uuid):
        """
        Deletes a server together with its attached CDROM drives, leaving disk drives intact.

        :param uuid:
            UUID of the server to delete.
        :type uuid: basestring
        :return:
            Response from the API.
        """
        return self.delete(uuid, recurse='cdroms')


